CREATE DATABASE abando_scope;

USE abando_scope;

CREATE TABLE brand_performance (
    brand VARCHAR(255),
    views BIGINT,
    carts BIGINT,
    purchases BIGINT,
    revenue DECIMAL(18,2)
);

CREATE TABLE category_performance (
    category_code VARCHAR(255),
    views BIGINT,
    carts BIGINT,
    purchases BIGINT,
    revenue DECIMAL(18,2)
);

CREATE TABLE event_distribution (
    event_type VARCHAR(50),
    event_count BIGINT
);

CREATE TABLE top_products (
    product_id BIGINT,
    views BIGINT,
    carts BIGINT,
    purchases BIGINT,
    revenue DECIMAL(18,2)
);

-- New table for session‑level KPIs generated by generate_session_kpis.py
CREATE TABLE session_kpis (
    metric VARCHAR(50) PRIMARY KEY,
    value DECIMAL(18,4)  -- stores integer counts or float values with up to 4 decimal places
);
